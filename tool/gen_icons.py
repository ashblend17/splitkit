#!/usr/bin/env python3
"""Generate the app icons (Android, iOS, web) from the brand mark.

The mark is the one in the sidebar and rail (`_BrandMark` in navigation.dart): the "settle"
glyph from sk_icon.dart, white on ink, the glyph's 24-unit grid at 18/32 of the tile.

Usage: python3 tool/gen_icons.py   (needs rsvg-convert and ImageMagick's magick)
"""

import json
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
APP = ROOT / "app"
RES = APP / "android" / "app" / "src" / "main" / "res"
IOS = APP / "ios" / "Runner" / "Assets.xcassets" / "AppIcon.appiconset"
WEB = APP / "web"

INK = "#15171C"  # tokens.json color.ink
ON_FILL = "#FFFFFF"  # color.onFill
GLYPH = "M8 3 4 7l4 4M4 7h16M16 21l4-4-4-4M20 17H4"  # sk_icon.dart 'settle'
GLYPH_ANDROID = "M8,3L4,7L8,11M4,7H20M16,21L20,17L16,13M20,17H4"  # the same, spelled out
STROKE = 1.8
GLYPH_SHARE = 18 / 32  # of the tile the glyph's grid takes
RADIUS = 10 / 32  # the sidebar mark's corners, for icons that aren't masked by the system

ANDROID_DENSITIES = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}
# Adaptive icons: 108dp layers, of which the launcher shows about the middle 72dp.
ADAPTIVE_LAYER, ADAPTIVE_SHOWN = 108, 72


def svg(rounded: bool) -> str:
    """The mark on a 1024 canvas: a rounded tile, or full bleed for icons the system masks."""
    size = 1024
    scale = GLYPH_SHARE * size / 24
    offset = size / 2 - 12 * scale
    rx = RADIUS * size if rounded else 0
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {size} {size}">'
        f'<rect width="{size}" height="{size}" rx="{rx}" fill="{INK}"/>'
        f'<path d="{GLYPH}" transform="translate({offset} {offset}) scale({scale})" fill="none" '
        f'stroke="{ON_FILL}" stroke-width="{STROKE}" stroke-linecap="round" stroke-linejoin="round"/>'
        "</svg>"
    )


def render(source: Path, out: Path, px: int, opaque: bool = False) -> None:
    out.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(["rsvg-convert", "-w", str(px), "-h", str(px), "-o", str(out), str(source)], check=True)
    if opaque:  # the App Store refuses an icon with an alpha channel
        subprocess.run(["magick", str(out), "-background", INK, "-alpha", "remove", "-alpha", "off", str(out)], check=True)


def android_xml() -> None:
    scale = GLYPH_SHARE * ADAPTIVE_SHOWN / 24
    offset = ADAPTIVE_LAYER / 2 - 12 * scale
    (RES / "drawable").mkdir(exist_ok=True)
    (RES / "drawable" / "ic_launcher_foreground.xml").write_text(
        f"""<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by tool/gen_icons.py. The launcher icon's mark: the "settle" arrows, white. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{ADAPTIVE_LAYER}dp"
    android:height="{ADAPTIVE_LAYER}dp"
    android:viewportWidth="{ADAPTIVE_LAYER}"
    android:viewportHeight="{ADAPTIVE_LAYER}">
    <group
        android:translateX="{offset:g}"
        android:translateY="{offset:g}"
        android:scaleX="{scale:g}"
        android:scaleY="{scale:g}">
        <path
            android:pathData="{GLYPH_ANDROID}"
            android:strokeColor="#FF{ON_FILL.lstrip('#')}"
            android:strokeWidth="{STROKE}"
            android:strokeLineCap="round"
            android:strokeLineJoin="round" />
    </group>
</vector>
""",
        encoding="utf-8",
    )
    (RES / "values" / "ic_launcher_background.xml").write_text(
        f"""<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by tool/gen_icons.py: tokens.json color.ink. -->
<resources>
    <color name="ic_launcher_background">{INK}</color>
</resources>
""",
        encoding="utf-8",
    )
    (RES / "mipmap-anydpi-v26").mkdir(exist_ok=True)
    (RES / "mipmap-anydpi-v26" / "ic_launcher.xml").write_text(
        """<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by tool/gen_icons.py. Android 8 and up; older ones use the PNGs. The monochrome
     layer is the themed icon on Android 13 and up. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_foreground" />
</adaptive-icon>
""",
        encoding="utf-8",
    )


def main() -> None:
    with tempfile.TemporaryDirectory() as tmp:
        rounded, bleed = Path(tmp) / "rounded.svg", Path(tmp) / "bleed.svg"
        rounded.write_text(svg(rounded=True), encoding="utf-8")
        bleed.write_text(svg(rounded=False), encoding="utf-8")

        for density, px in ANDROID_DENSITIES.items():
            render(rounded, RES / f"mipmap-{density}" / "ic_launcher.png", px)
        android_xml()

        for image in json.loads((IOS / "Contents.json").read_text(encoding="utf-8"))["images"]:
            points = float(image["size"].split("x")[0])
            px = round(points * int(image["scale"].rstrip("x")))
            render(bleed, IOS / image["filename"], px, opaque=True)

        render(rounded, WEB / "favicon.png", 32)
        for px in (192, 512):
            render(rounded, WEB / "icons" / f"Icon-{px}.png", px)
            render(bleed, WEB / "icons" / f"Icon-maskable-{px}.png", px)


if __name__ == "__main__":
    main()
